"""Compile the icon set to ``ui/assets/30-icons.css`` (CSS mask icons: they inherit ``currentColor``).

    python -m cxdash.devtools.build_icons

Icons are 24x24 stroke glyphs. Using CSS masks keeps the CSP strict (data: images only), needs no JS or font,
and lets every icon follow the surrounding text colour in both themes. ``ICONS`` is the single source of truth;
``ui/components/icons.py`` validates names against it.
"""

from __future__ import annotations

from pathlib import Path
from urllib.parse import quote

from cxdash.ui.icon_set import ICONS


def svg(name: str) -> str:
    body = ICONS[name]
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="black" '
        f'stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">{body}</svg>'
    )


def build_css() -> str:
    lines = [
        "/* GENERATED by `python -m cxdash.devtools.build_icons` - do not edit by hand. */",
        ".cx-icon{display:inline-block;width:1.15em;height:1.15em;flex:none;vertical-align:-0.2em;background-color:currentColor;"
        "-webkit-mask:var(--cx-icon) center/contain no-repeat;mask:var(--cx-icon) center/contain no-repeat}",
    ]
    for name in ICONS:
        lines.append(f'.cx-icon-{name}{{--cx-icon:url("data:image/svg+xml,{quote(svg(name), safe="/:=")}")}}')
    return "\n".join(lines) + "\n"


def main() -> None:
    target = Path(__file__).resolve().parents[1] / "ui" / "assets" / "30-icons.css"
    target.write_text(build_css(), encoding="utf-8")
    print(f"wrote {target} ({len(ICONS)} icons)")


if __name__ == "__main__":
    main()
